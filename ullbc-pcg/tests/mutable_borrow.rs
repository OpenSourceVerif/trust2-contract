#[test]
fn shared_reference_assignment_adds_flow_instead_of_retargeting_borrow() {
    let body = fixture("shared_aliases");
    let (r, s) = (local(&body, "r"), local(&body, "s"));
    let result = analyze(&body).unwrap();
    let point = result
        .points
        .iter()
        .find(|p| {
            p.after()
                .edges
                .iter()
                .any(|e| matches!(e, Edge::BorrowFlow { .. }))
        })
        .unwrap();
    assert!(
        point
            .after()
            .edges
            .iter()
            .any(|e| matches!(e, Edge::Borrow { assigned, .. } if assigned.reference == r))
    );
    assert!(point.after().edges.iter().any(|e| matches!(e, Edge::BorrowFlow { from, to, operand: OperandKind::Copy } if from.reference == r && to.reference == s && from.base_label.is_none())));
    assert_eq!(
        point.after().capability(Place::Local(local(&body, "x"))),
        Some(Capability::Read)
    );
}
#[test]
fn moving_reference_labels_old_value_then_connects_borrow_flow() {
    let body = fixture("moved_reference");
    let (r, s) = (local(&body, "r"), local(&body, "s"));
    let result = analyze(&body).unwrap();
    let movement = result
        .points
        .iter()
        .find(|p| {
            p.actions().any(|a| {
                matches!(
                    a.action,
                    Action::AddEdge {
                        edge: Edge::BorrowFlow {
                            operand: OperandKind::Move,
                            ..
                        }
                    }
                )
            })
        })
        .unwrap();
    let post = &movement.phase(Phase::PostOperands).after;
    assert_eq!(post.capability(Place::Local(r)), Some(Capability::Write));
    assert!(post.edges.iter().any(|e| matches!(e, Edge::Borrow { assigned, .. } if assigned.base_label == Some(Snapshot { location: movement.location, phase: Phase::PostOperands }))));
    assert!(movement.after().edges.iter().any(|e| matches!(e, Edge::BorrowFlow { from, to, operand: OperandKind::Move } if from.base_label.is_some() && to.reference == s)));
    assert!(!movement.actions().any(|a| matches!(
        a.action,
        Action::RemoveEdge {
            edge: Edge::Borrow { .. }
        }
    )));
}
