use charon_lib::{
    ast::{Body, LocalId},
    export::CrateData,
    formatter::IntoFormatter,
    pretty::FmtWithCtx,
    ullbc_ast as u,
};
use ullbc_pcg::{
    Action, Capability, CapabilityReason, Edge, ErrorKind, EvalStmtPhase as Phase, OperandKind,
    Place, Snapshot,
};

struct Fixture {
    ir: u::ExprBody,
    facts: charon_lib::ast::BodyBorrowckInfo,
}
impl std::ops::Deref for Fixture {
    type Target = u::ExprBody;
    fn deref(&self) -> &Self::Target {
        &self.ir
    }
}
impl std::ops::DerefMut for Fixture {
    fn deref_mut(&mut self) -> &mut Self::Target {
        &mut self.ir
    }
}
fn analyze(input: &Fixture) -> Result<ullbc_pcg::Analysis, ullbc_pcg::AnalysisError> {
    ullbc_pcg::analyze(&input.ir, &input.facts)
}
fn fixture(name: &str) -> Fixture {
    let text = if name == "mutable_borrow" {
        include_str!("fixtures/mutable_borrow.ullbc")
    } else if name == "repeated_write" {
        include_str!("fixtures/cfg_borrows.ullbc")
    } else {
        include_str!("fixtures/borrows.ullbc")
    };
    let data: CrateData = serde_json::from_str(text).unwrap();
    assert!(!data.has_errors);
    let fmt = (&data.translated).into_fmt();
    let function = data
        .translated
        .fun_decls
        .iter()
        .find(|f| {
            f.item_meta
                .name
                .to_string_with_ctx(&fmt)
                .ends_with(&format!("::{name}"))
        })
        .unwrap();
    let Body::Unstructured(body) = &function.body else {
        panic!("expected real ULLBC")
    };
    Fixture {
        ir: body.clone(),
        facts: data
            .translated
            .borrowck
            .as_ref()
            .unwrap()
            .bodies
            .iter()
            .find(|b| b.function_id == function.def_id)
            .unwrap()
            .clone(),
    }
}
fn local(body: &u::ExprBody, name: &str) -> LocalId {
    body.locals
        .locals
        .iter_enumerated()
        .find(|(_, l)| l.name.as_deref() == Some(name))
        .unwrap()
        .0
}

// Expected phase boundaries below come from the pinned MIR-PCG rules,
// not from snapshots generated by the implementation under test.
#[test]
fn borrow_operand_postcondition_precedes_post_main_borrow_edge() {
    let body = fixture("mutable_borrow");
    let (x, r) = (local(&body, "x"), local(&body, "r"));
    let result = analyze(&body).unwrap();
    let borrow = &result.points[4];
    assert_eq!(
        borrow
            .phase(Phase::PreOperands)
            .after
            .capability(Place::Local(x)),
        Some(Capability::Exclusive)
    );
    let post_operands = &borrow.phase(Phase::PostOperands).after;
    assert_eq!(post_operands.capability(Place::Local(x)), None);
    assert_eq!(post_operands.borrows().count(), 0);
    assert_eq!(
        borrow
            .phase(Phase::PreMain)
            .after
            .capability(Place::Local(r)),
        Some(Capability::Write)
    );
    assert_eq!(
        borrow.after().capability(Place::Local(r)),
        Some(Capability::Exclusive)
    );
    assert_eq!(
        borrow.after().capability(Place::Deref(r)),
        None,
        "borrowing must not eagerly expand *r"
    );
    assert!(
        matches!(&borrow.after().edges[..], [Edge::Borrow { assigned, .. }] if assigned.reference == r && assigned.label.is_none())
    );
}

#[test]
fn deref_is_obtained_on_demand_then_target_is_weakened_and_initialized() {
    let body = fixture("mutable_borrow");
    let r = local(&body, "r");
    let result = analyze(&body).unwrap();
    let write = &result.points[5];
    assert_eq!(
        write
            .phase(Phase::PostOperands)
            .after
            .capability(Place::Deref(r)),
        None
    );
    let pre = write.phase(Phase::PreMain);
    assert_eq!(
        pre.after.capability(Place::Local(r)),
        Some(Capability::ShallowExclusive)
    );
    assert_eq!(
        pre.after.capability(Place::Deref(r)),
        Some(Capability::Write)
    );
    let expand = pre
        .actions
        .iter()
        .position(|a| {
            matches!(
                a.action,
                Action::AddEdge {
                    edge: Edge::Deref { .. }
                }
            )
        })
        .unwrap();
    let weaken = pre.actions.iter().position(|a| matches!(a.action, Action::SetCapability { place: Place::Deref(id), from: Some(Capability::Exclusive), to: Some(Capability::Write), reason: CapabilityReason::PrepareWrite } if id == r)).unwrap();
    assert!(expand < weaken);
    assert!(pre.after.edges.iter().any(|e| matches!(e, Edge::Borrow { assigned, .. } if assigned.label == Some(Snapshot { location: write.location, phase: Phase::PreMain }))));
    assert_eq!(
        write.after().capability(Place::Deref(r)),
        Some(Capability::Exclusive)
    );
    assert!(!write.live_references_after.contains(&r));
}

#[test]
fn pack_removes_deref_then_borrow_then_obtains_owner_read() {
    let body = fixture("mutable_borrow");
    let (x, r) = (local(&body, "x"), local(&body, "r"));
    let result = analyze(&body).unwrap();
    let read = &result.points[6];
    let pre = read.phase(Phase::PreOperands);
    let deref = pre
        .actions
        .iter()
        .position(|a| {
            matches!(
                a.action,
                Action::RemoveEdge {
                    edge: Edge::Deref { .. }
                }
            )
        })
        .unwrap();
    let borrow = pre
        .actions
        .iter()
        .position(|a| {
            matches!(
                a.action,
                Action::RemoveEdge {
                    edge: Edge::Borrow { .. }
                }
            )
        })
        .unwrap();
    let access = pre.actions.iter().position(|a| matches!(a.action, Action::Require { place: Place::Local(id), capability: Capability::Read } if id == x)).unwrap();
    assert!(deref < borrow && borrow < access);
    assert_eq!(
        pre.after.capability(Place::Local(x)),
        Some(Capability::Exclusive)
    );
    assert_eq!(
        pre.after.capability(Place::Local(r)),
        Some(Capability::Write),
        "upstream weakens the dead assigned reference"
    );
    assert_eq!(pre.after.capability(Place::Deref(r)), None);
    assert!(pre.after.edges.is_empty());
}

#[test]
fn live_reference_is_reexpanded_without_releasing_its_borrow() {
    let body = fixture("repeated_write");
    let (x, r) = (local(&body, "x"), local(&body, "r"));
    let result = analyze(&body).unwrap();
    let second_write = &result.points[6];
    let pre = second_write.phase(Phase::PreOperands);
    assert_eq!(pre.after.capability(Place::Local(x)), None);
    assert_eq!(pre.after.capability(Place::Deref(r)), None);
    assert_eq!(pre.after.borrows().count(), 1);
    assert!(pre.actions.iter().any(|a| matches!(
        a.action,
        Action::RemoveEdge {
            edge: Edge::Deref { .. }
        }
    )));
    assert!(!second_write.actions().any(|a| matches!(
        a.action,
        Action::RemoveEdge {
            edge: Edge::Borrow { .. }
        }
    )));
    assert!(
        second_write
            .phase(Phase::PreMain)
            .actions
            .iter()
            .any(|a| matches!(
                a.action,
                Action::AddEdge {
                    edge: Edge::Deref { .. }
                }
            ))
    );
}

#[test]
fn old_reference_projection_survives_while_live_destination_depends_on_it() {
    let body = fixture("moved_reference");
    let (x, r, s) = (local(&body, "x"), local(&body, "r"), local(&body, "s"));
    let result = analyze(&body).unwrap();
    let use_s = result.points.iter().find(|p| p.actions().any(|a|
        matches!(a.action, Action::AddEdge { edge: Edge::Deref { reference, .. } } if reference == s))).unwrap();
    let graph = &use_s.phase(Phase::PreOperands).after;
    assert_eq!(graph.capability(Place::Local(x)), None);
    assert!(
        graph.edges.iter().any(|e| matches!(e,
        Edge::Borrow { assigned, .. } if assigned.reference == r && assigned.base_label.is_some()))
    );
    assert!(graph.edges.iter().any(|e| matches!(e,
        Edge::BorrowFlow { from, to, .. } if from.reference == r && to.reference == s)));
}

#[test]
fn capability_order_keeps_read_and_shallow_exclusive_incomparable() {
    use Capability::*;
    assert!(Exclusive.permits(Read) && Exclusive.permits(ShallowExclusive));
    assert!(ShallowExclusive.permits(Write));
    assert!(!ShallowExclusive.permits(Read));
    assert!(!Read.permits(ShallowExclusive));
    assert!(!Read.permits(Write) && !Write.permits(Read));
}

#[test]
fn four_phases_and_action_snapshots_form_a_continuous_trace() {
    for name in [
        "mutable_borrow",
        "shared_borrow",
        "moved_reference",
        "shared_aliases",
        "scalar_argument",
    ] {
        let result = analyze(&fixture(name)).unwrap();
        for point in &result.points {
            assert_eq!(
                point.phases.iter().map(|p| p.phase).collect::<Vec<_>>(),
                Phase::phases()
            );
            let mut previous = &point.initial;
            for phase in &point.phases {
                assert_eq!(previous, &phase.before);
                let mut graph = &phase.before;
                for applied in &phase.actions {
                    if let Action::Require { place, capability } = applied.action {
                        assert!(
                            graph
                                .capability(place)
                                .is_some_and(|k| k.permits(capability))
                        );
                        assert_eq!(graph, &applied.after);
                    }
                    graph = &applied.after;
                }
                assert_eq!(graph, &phase.after);
                previous = &phase.after;
            }
        }
        for adjacent in result.points.windows(2) {
            assert_eq!(adjacent[0].after(), &adjacent[1].initial);
        }
    }
}

